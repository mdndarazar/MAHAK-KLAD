/** اطلاعات یک حالت؛ حالت نامعتبر ⇒ اطلاعات «الف» تا UI هرگز خالی نماند. */
export function diagnoseModeInfo(mode: unknown): DiagnoseModeInfo {
  const key = String(mode ?? 'A').trim().toUpperCase()
  return DIAGNOSE_MODES.find((m) => m.mode === key) ?? DIAGNOSE_MODES[0]
}
