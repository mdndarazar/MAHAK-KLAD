-- ۱) isWholesale (مورد ۶): مشتری‌ای که از «ثبت سریع خریدار» پنل فاکتور فروش
--    عمده — یا از پنل مشتریانِ تنظیمات با نوع «عمده» — ثبت می‌شود true می‌گیرد.
--    فیلد جستجوی خریدار در پنل عمده فقط همین‌ها (به‌علاوه‌ی «مشتری عمومی») را
--    نشان می‌دهد و مشتری‌های تکیِ پنل فروش دیگر آنجا دیده نمی‌شوند.
--    ⚠️ پیش‌فرض false است، پس همه‌ی مشتری‌های *موجود* «تکی» می‌مانند و هیچ
--    داده‌ای تغییر نمی‌کند؛ نوع هر مشتری از پنل مشتریانِ تنظیمات با یک کلیک
--    قابل تغییر است.
--
-- ۲) manualPurchaseTotal (مورد ۳): «مجموع مبلغ خرید» که مدیر دستی ثبت می‌کند
--    (برای مشتری‌ای که سابقه‌اش در برنامه نیست). جمع خرید نمایشی = جمع
--    فاکتورهای ثبت‌شده + همین عدد. پیش‌فرض صفر ⇒ هیچ گزارشی عوض نمی‌شود.
--
-- ۳) دو ایندکس: جستجوی مشتری با شماره تلفن (جلوگیری از رکورد تکراری در لحظه‌ی
--    ثبت فاکتور) و فهرست مشتری‌های عمده.
