/**
 * ===========================================================================
 * نشست ۱۷۴ · مشاهده‌ی P3 ممیزی ۸۸/۱۱۶ — «پاسخ کهنه» (همان الگوی A88-01، یک‌جا و قابل تست).
 *
 * پنل‌های گزارش (OutOfShiftPanel، CardTransferPanel، OverrideSessionsPanel) و MovementsModal با
 * هر تغییر بازه/فیلتر/کالا/صفحه یک درخواست تازه می‌فرستادند و پاسخ *هر* درخواست را روی صفحه
 * می‌نشاندند. اگر درخواست قبلی دیرتر برمی‌گشت (بازه‌ی بزرگ‌تر = کندتر)، عددِ بازه/کالای قبلی زیر
 * عنوان بازه/کالای فعلی می‌نشست و Excel هم با نام بازه‌ی فعلی همان ردیف‌های کهنه را می‌نوشت.
 *
 * قاعده: هر درخواست شماره می‌گیرد (next)؛ فقط پاسخ/خطا/پایان آخرین شماره (isLatest) روی state
 * می‌نشیند. تابع خالص و بی‌وابستگی به React است تا تست Node رفتارش را مستقیم بسنجد.
 * ===========================================================================
 */
export interface LatestGate {
  /** شماره‌ی درخواست تازه؛ هر درخواست قبلی از این لحظه «کهنه» است. */
  next(): number
  /** آیا این شماره هنوز آخرین درخواست است؟ (پاسخ/خطا/busy فقط در این حالت اعمال شود) */
  isLatest(seq: number): boolean
  /** همه‌ی درخواست‌های در جریان را کهنه می‌کند (مثلاً بستن مودال). */
  invalidate(): void
}

export function createLatestGate(): LatestGate {
  let current = 0
  return {
    next: () => ++current,
    isLatest: (seq: number) => seq === current,
    invalidate: () => {
      current++
    }
  }
}
