/**
 * نشست ۳۱۶ · خواسته‌ی مالک — ورودی‌های مبلغ هنگام تایپ سه‌رقم‌سه‌رقم جدا شوند
 * («10000000 خوانا نیست؛ باید ۱۰٬۰۰۰٬۰۰۰ دیده شود»).
 *
 * الگو: state فیلد همیشه «رقم‌های خامِ لاتین» است (تا `Number(...)` سمت ارسال
 * و هر منطقِ موجود دست‌نخورده بماند) و فقط *نمایشِ* داخل input گروه‌بندی می‌شود.
 * ارقام نمایشی لاتین می‌مانند تا با `dir=ltr` جای گروه‌ها برعکس نشود.
 */
import { toLatinDigits } from '@shared/jalali'

/** هر رقمی (لاتین/فارسی/عربی) را به رقم لاتینِ پشت‌سرهم تبدیل می‌کند؛ غیررقم حذف. */
export function digitsOnly(s: string): string {
  return toLatinDigits(String(s ?? '')).replace(/\D/g, '')
}

/**
 * نمایش گروه‌بندی‌شده‌ی رقم‌های خام: «10000000» ⇒ «10٬000٬000».
 * صفرهای ابتدایی حذف می‌شوند («۰۰۷» ⇒ «7») اما خودِ صفرِ تنها «0» می‌ماند تا
 * کاربر بفهمد چیزی تایپ کرده. ورودی خالی ⇒ خالی (placeholder دیده می‌شود).
 */
export function groupThousands(raw: string): string {
  const d = digitsOnly(raw).replace(/^0+(?=\d)/, '')
  return d.replace(/\B(?=(\d{3})+(?!\d))/g, '٬')
}
