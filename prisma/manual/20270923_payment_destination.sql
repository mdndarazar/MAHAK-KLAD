-- جلسه ۳۶ · کار الف — «مقصد پولِ چک پاس‌شده و پرداختی نسیه».
--
-- پولی که *از مشتری* می‌گیریم (چک پاس‌شده یا پرداختی نسیه) تا امروز جای
-- مشخصی نداشت: چک با روش «CHEQUE» (kind = CUSTOM) ثبت می‌شد، در تفکیک گزارش به
-- سبد «سایر» می‌رفت و بعد در بستن صندوق با `cardTotal + otherTotal` بی‌صدا به
-- «انتظار کارتخوان» اضافه می‌شد — *در حالی که همان مبلغ از راه
-- `clearedCashChequeAmount` به «انتظار نقد» هم اضافه شده بود*. یعنی هر چک
-- پاس‌شده دو بار شمرده می‌شد و هنگام بستن صندوق کسری/اضافه‌ی بی‌دلیل می‌ساخت.
--
-- قاعده‌ی همیشگی پروژه رعایت شده است: فقط یک ستون *جدید و Nullable* اضافه
-- می‌شود. هیچ ستونی حذف نمی‌شود، هیچ نوعی عوض نمی‌شود، هیچ ردیفی پاک یا
-- به‌روزرسانی نمی‌شود. پس روی دیتابیس پرِ فروشگاه امن است و همه‌ی پرداختی‌ها و
-- چک‌های قبلی `destination = NULL` می‌مانند («نامشخص»). عمداً هیچ UPDATE
-- حدسی‌ای اینجا نیست: اگر برای داده‌ی قدیمی مقصد حدس می‌زدیم، عدد گزارش‌های
-- گذشته عوض می‌شد.
--
-- مقادیر مجاز ستون: 'CARD' | 'CASH' | 'MANAGER'  (تعریف در src/shared/enums.ts)
-- -----------------------------------------------------------------------------
ALTER TABLE "Payment" ADD COLUMN "destination" TEXT;

-- تفکیک دریافتی‌ها بر اساس مقصد (گزارش فروش، بستن صندوق، جزئیات شیفت)
CREATE INDEX IF NOT EXISTS "Payment_destination_idx" ON "Payment"("destination");

-- «چکِ پاس‌شده‌ی این بازه، به تفکیک مقصد» — کوئری بلوک چکِ گزارش فروش و
-- محاسبه‌ی `clearedCashChequeAmount` بستن صندوق روی همین دو ستون می‌نشیند.
CREATE INDEX IF NOT EXISTS "Payment_clearedAt_destination_idx" ON "Payment"("clearedAt", "destination");
