export type DiagnoseMode = 'A' | 'B' | 'C' | 'D' | 'E'

export interface DiagnoseModeInfo {
  mode: DiagnoseMode
  /** عنوانی که هم در فهرست تنظیمات و هم روی برگه‌ی چاپی می‌آید */
  title: string
  /** یک خط توضیح: این آزمایش چه چیزی را می‌سنجد */
  hint: string
  /** مقادیر پیشنهادی برای همان آزمایش */
  defaults: { widthMm: number; heightMm: number; columns: number; gapXMm: number }
}

